// FR-10.3 — Auto-PR creation: push evergreen/* branch + open PR with evidence report
import { Octokit } from "@octokit/rest";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { BreakingChangeSpec, ScanResult, specRef, ChangeManifest } from "../types.js";

const run = promisify(execFile);

export interface AutoPRResult {
  branch: string;
  prNumber: number;
  prUrl: string;
}

export async function createMigrationPR(
  octokit: Octokit,
  owner: string,
  repo: string,
  baseBranch: string,
  cloneDir: string,
  token: string,
  spec: BreakingChangeSpec,
  scan: ScanResult,
  manifest: ChangeManifest,
): Promise<AutoPRResult> {
  const branch = `evergreen/${spec.vendor}-${spec.api}-${spec.version}`.replace(/[^a-zA-Z0-9/_-]/g, "-");

  await run("git", ["-C", cloneDir, "checkout", "-b", branch], { timeout: 10_000 });
  await run("git", ["-C", cloneDir, "add", "-A"], { timeout: 10_000 });

  const commitMsg = [
    `fix: migrate ${spec.api} to ${spec.version}`,
    "",
    `Auto-migration by Evergreen — ${spec.title}`,
    `Spec: ${specRef(spec)}`,
    `Findings: ${scan.findings.length} location(s) across ${new Set(scan.findings.map((f) => f.file)).size} file(s)`,
    `Files migrated: ${manifest.files.filter((f) => f.status === "migrated").length}`,
    `Files skipped: ${manifest.files.filter((f) => f.status === "skipped").length}`,
  ].join("\n");

  await run("git", ["-C", cloneDir, "commit", "-m", commitMsg], { timeout: 30_000 });

  const pushUrl = `https://x-access-token:${token}@github.com/${owner}/${repo}.git`;
  await run("git", ["-C", cloneDir, "push", pushUrl, branch], { timeout: 60_000 });

  const body = buildPRBody(spec, scan, manifest);
  const { data: pr } = await octokit.pulls.create({
    owner,
    repo,
    title: `[Evergreen] Migrate ${spec.api} to ${spec.version}`,
    head: branch,
    base: baseBranch,
    body,
  });

  return { branch, prNumber: pr.number, prUrl: pr.html_url };
}

function buildPRBody(spec: BreakingChangeSpec, scan: ScanResult, manifest: ChangeManifest): string {
  const migratedFiles = manifest.files.filter((f) => f.status === "migrated");
  const skippedFiles = manifest.files.filter((f) => f.status === "skipped");
  const partialFiles = manifest.files.filter((f) => f.status === "partial");

  const lines: string[] = [
    `## Evergreen Auto-Migration: ${spec.title}`,
    "",
    `> Automated migration generated by [Evergreen](https://github.com/ankitjha67/evergreen) in response to a breaking API change.`,
    "",
    `| | |`,
    `|---|---|`,
    `| **Vendor** | ${spec.vendor} |`,
    `| **API** | ${spec.api} |`,
    `| **Target version** | ${spec.version} |`,
    spec.deadline ? `| **Vendor deadline** | ${spec.deadline} |` : "",
    `| **Spec** | \`${specRef(spec)}\` |`,
    `| **Findings** | ${scan.findings.length} location(s) in ${new Set(scan.findings.map((f) => f.file)).size} file(s) |`,
    `| **Model** | ${manifest.engine.model} |`,
    "",
    "### Migration Summary",
    "",
    `- **Migrated:** ${migratedFiles.length} file(s)`,
    `- **Skipped:** ${skippedFiles.length} file(s)`,
    `- **Partial:** ${partialFiles.length} file(s)`,
    "",
  ].filter(Boolean);

  if (migratedFiles.length > 0) {
    lines.push(
      "### Migrated Files",
      "",
      "| File | Rules | Confidence | Summary |",
      "|---|---|---|---|",
    );
    for (const f of migratedFiles) {
      lines.push(`| \`${f.path}\` | ${f.rules.join(", ")} | ${(f.confidence * 100).toFixed(0)}% | ${f.summary} |`);
    }
    lines.push("");
  }

  if (skippedFiles.length > 0) {
    lines.push(
      "### Skipped Files",
      "",
      "| File | Reason |",
      "|---|---|",
    );
    for (const f of skippedFiles) {
      lines.push(`| \`${f.path}\` | ${f.reasons?.join("; ") ?? "No reason provided"} |`);
    }
    lines.push("");
  }

  if (manifest.notes) {
    lines.push("### Notes", "", manifest.notes, "");
  }

  lines.push(
    "---",
    "",
    "**Review carefully.** This migration was generated by an AI agent. While the agent follows a minimal-diff contract and validates its changes, human review is essential before merging.",
    "",
    "Please verify:",
    "- [ ] All migrated code compiles/passes lint",
    "- [ ] Tests pass",
    "- [ ] No unintended behavioral changes",
    "- [ ] Skipped files have been addressed manually if needed",
  );

  return lines.join("\n");
}
