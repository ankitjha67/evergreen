// FR-05.2 / FR-06 — MIGRATION_REPORT.md generator
import { BreakingChangeSpec, MigrationOutcome } from "../types.js";

export function renderReport(outcome: MigrationOutcome, spec: BreakingChangeSpec): string {
  const L: string[] = [];
  L.push(`# Evergreen Migration Report`);
  L.push(`**Spec:** ${outcome.specRef} — ${spec.title}`);
  if (spec.docsUrl) L.push(`**Upgrade guide:** ${spec.docsUrl}`);
  if (spec.deadline) L.push(`**Vendor deadline:** ${spec.deadline}`);
  L.push(`**Status:** ${outcome.status}${outcome.branch ? ` | **Branch:** \`${outcome.branch}\`` : ""}`);
  L.push("");

  L.push(`## Scan`);
  L.push(
    `${outcome.scan.findings.length} finding(s) across ${new Set(outcome.scan.findings.map((f) => f.file)).size} file(s); ${outcome.scan.scannedFiles} files scanned in ${outcome.scan.durationMs}ms.`,
  );
  L.push("");

  if (outcome.manifest) {
    L.push(`## Changes`);
    L.push(`| File | Rules | Status | Confidence | Summary |`);
    L.push(`|---|---|---|---|---|`);
    for (const f of outcome.manifest.files) {
      L.push(`| \`${f.path}\` | ${f.rules.join(", ")} | ${f.status} | ${f.confidence.toFixed(2)} | ${f.summary.replace(/\|/g, "\\|")} |`);
    }
    L.push("");
    const skipped = outcome.manifest.files.filter((f) => f.status !== "migrated");
    if (skipped.length > 0) {
      L.push(`### Skipped / partial — needs human attention`);
      for (const f of skipped) L.push(`- \`${f.path}\`: ${(f.reasons ?? []).join("; ") || "no reason given"}`);
      L.push("");
    }
    if (outcome.manifest.notes) {
      L.push(`### Agent notes`);
      L.push(outcome.manifest.notes);
      L.push("");
    }
  }

  if (outcome.triage) {
    L.push(`## Triage (FR-03.2)`);
    if (outcome.triage.degraded) L.push(`⚠ Triage degraded (${outcome.triage.degraded}) — all findings kept conservatively.`);
    L.push(`| Location | Rule | Verdict | Reason |`);
    L.push(`|---|---|---|---|`);
    for (const v of outcome.triage.verdicts) {
      L.push(`| \`${v.file}:${v.line}\` | ${v.ruleId} | ${v.verdict} | ${v.reason.replace(/\|/g, "\\|")} |`);
    }
    L.push("");
  }

  if (outcome.gated.length > 0) {
    L.push(`## Confidence-gated (reverted, review manually) — FR-04.5`);
    for (const g of outcome.gated) L.push(`- \`${g.path}\` (confidence ${g.confidence.toFixed(2)} below threshold)`);
    L.push("");
  }

  if (outcome.violations.length > 0) {
    L.push(`## Scope violations (reverted automatically)`);
    for (const v of outcome.violations) L.push(`- ${v}`);
    L.push("");
  }

  if (outcome.verify) {
    L.push(`## Verification`);
    L.push(`\`${outcome.verify.command}\` → exit ${outcome.verify.exitCode}`);
    L.push("```\n" + outcome.verify.tail + "\n```");
    L.push("");
  }

  L.push(`## Rules applied`);
  for (const c of spec.changes) {
    const used = outcome.scan.findings.some((f) => f.ruleId === c.id);
    if (!used) continue;
    L.push(`### ${c.id} — ${c.title} [${c.severity}]`);
    L.push(c.description);
    if (c.replace.before && c.replace.after) {
      L.push(`**Before:**\n\`\`\`\n${c.replace.before}\n\`\`\`\n**After:**\n\`\`\`\n${c.replace.after}\n\`\`\``);
    }
    if (c.replace.docsUrl) L.push(`Docs: ${c.replace.docsUrl}`);
    L.push("");
  }

  if (outcome.usage) {
    L.push(`## Run economics`);
    L.push(
      `Tokens — input: ${outcome.usage.inputTokens.toLocaleString()} | cache read: ${outcome.usage.cacheReadTokens.toLocaleString()} | cache write: ${outcome.usage.cacheCreationTokens.toLocaleString()} | output: ${outcome.usage.outputTokens.toLocaleString()} — inference cost $${outcome.usage.costUSD}`,
    );
    L.push("");
  }

  L.push(`## Review checklist`);
  L.push(`- [ ] Diff touches only expected files`);
  L.push(`- [ ] Parameter/return-shape mappings match the vendor guide`);
  L.push(`- [ ] Tests pass locally`);
  L.push(`- [ ] Skipped locations handled manually (if any)`);
  L.push("");
  L.push(`*Generated by Evergreen. PRs, never pushes — a human merges.*`);
  return L.join("\n");
}
